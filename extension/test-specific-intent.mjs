import assert from 'node:assert/strict';
import {parseIntent,filterReason,positiveSearchQuery,summariseIntent} from './intent.mjs';
const policy=prompt=>({preferences:{},active:{intent:{prompt,plan:{include:['Animals'],exclude:[],includeTerms:[],excludeTerms:[]},mode:'both',focused:true,strict:false}}});
const animal=text=>({category:'Animals',matchText:text,analysis:{kind:'Unknown'}});
assert.deepEqual(parseIntent('dogs').include,[]);
assert.deepEqual(parseIntent('dogs').includeTerms,['dog']);
for(const word of ['dog','dogs','puppy','puppies','canine']) assert.equal(filterReason(policy('dogs'),animal(word)),'');
for(const text of ['cats kittens','cute pets','an animal']) assert.ok(filterReason(policy('dogs'),animal(text)),'cats/generic animal labels do not satisfy dog-specific request');
assert.equal(filterReason(policy('animals'),animal('cats')),'','generic animals still includes cats');
assert.ok(filterReason(policy('no dogs'),animal('a puppy')));
assert.equal(filterReason(policy('no dogs'),animal('a kitten')),'','dog exclusion does not exclude all animals');
assert.match(summariseIntent(parseIntent('dogs'),'both'),/More: dog/);
assert.equal(positiveSearchQuery('dogs, less politics'),'dogs');
assert.equal(positiveSearchQuery('show cats but no dogs'),'cats');
assert.equal(positiveSearchQuery('only puppies'),'puppies');
assert.equal(positiveSearchQuery('no politics'),'');
assert.equal(positiveSearchQuery(''),'');
assert.equal(positiveSearchQuery('dogs and cats'),'dogs cats');
assert.equal(positiveSearchQuery('I want nature videos and dogs'),'nature dogs');
assert.equal(positiveSearchQuery('I have depression, show dogs'),'dogs','do not send mood/medical context as the search topic');
console.log('Passed species-specific intent, existing-prompt reinterpretation, generic animals, exclusions and positive topic-only search queries.');
